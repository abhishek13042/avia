"""Build a one-file Kaggle kernel that scores a trained model.

Kernels cannot see this repo, so the script carries src/avia and scripts/evaluate.py as a zip.
A kernel cannot keep the test log, so --test spends the budget here, in artifacts/test_log.json.

    python kaggle/t24_eval/build_kernel.py --fold 5 --out OUT_DIR
    python kaggle/t24_eval/build_kernel.py --test --note WHY --out OUT_DIR
    python -m kaggle kernels push -p OUT_DIR
"""
import argparse
import base64
import io
import json
import os
import sys
import zipfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OWNER = "abhishekg14"
sys.path.insert(0, os.path.join(ROOT, "src"))

from avia.data import splits

TEMPLATE = '''"""Generated by kaggle/t24_eval/build_kernel.py; edit that file instead."""
import base64
import io
import os
import runpy
import sys
import zipfile

ARGS = {args!r}
INPUT = os.environ.get("AVIA_INPUT", "/kaggle/input")
OUT = os.environ.get("AVIA_OUT", "/kaggle/working")
CODE = "{code}"


def find(name, want_dir):
    for root, dirs, files in os.walk(INPUT, followlinks=True):
        if name in (dirs if want_dir else files):
            return os.path.join(root, name)
    raise FileNotFoundError(name)


code_dir = os.path.join(OUT, "code")
zipfile.ZipFile(io.BytesIO(base64.b64decode(CODE))).extractall(code_dir)
detector = os.environ.get("AVIA_DETECTOR") or "maskrcnn:" + find("model.pt", False)
os.chdir(OUT)
os.makedirs("artifacts", exist_ok=True)
sys.argv = ["evaluate.py", "--data", find("APPLE_MOTS", True), "--detector", detector,
            "--out", os.path.join(OUT, "eval"), *ARGS]
runpy.run_path(os.path.join(code_dir, "scripts", "evaluate.py"), run_name="__main__")
'''


def bundle() -> str:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(os.path.join(ROOT, "scripts", "evaluate.py"), "scripts/evaluate.py")
        for folder, _, names in os.walk(os.path.join(ROOT, "src", "avia")):
            for name in names:
                if name.endswith(".py"):
                    path = os.path.join(folder, name)
                    z.write(path, os.path.relpath(path, ROOT).replace(os.sep, "/"))
    return base64.b64encode(buffer.getvalue()).decode()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--fold", type=int, choices=range(6))
    parser.add_argument("--test", action="store_true")
    parser.add_argument("--note", default="")
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    if args.test == (args.fold is not None):
        parser.error("give either --fold or --test")
    if args.test and not args.note:
        parser.error("--test needs --note saying why this evaluation is being spent")

    os.makedirs(args.out, exist_ok=True)
    source = "avia-t24-final" if args.test else f"avia-t24-fold{args.fold}"
    if args.test:
        used = splits.record_test_evaluation(os.path.join(ROOT, "artifacts", "test_log.json"),
                                             args.note)
        print(f"test evaluation {used} of {splits.MAX_TEST_EVALUATIONS}")
    kernel_args = ["--test", "--note", args.note] if args.test else ["--sequences", str(args.fold)]
    name = f"{source}-eval"
    with open(os.path.join(args.out, "avia_eval.py"), "w", encoding="utf-8") as f:
        f.write(TEMPLATE.format(args=kernel_args, code=bundle()))
    metadata = {
        "id": f"{OWNER}/{name}", "title": name, "code_file": "avia_eval.py",
        "language": "python", "kernel_type": "script", "is_private": True,
        "enable_gpu": True, "enable_internet": False,
        "dataset_sources": [f"{OWNER}/apple-mots"], "competition_sources": [],
        "kernel_sources": [f"{OWNER}/{source}"],
    }
    with open(os.path.join(args.out, "kernel-metadata.json"), "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)


if __name__ == "__main__":
    main()
